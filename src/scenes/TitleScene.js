import Phaser from 'phaser';
import { GAME_W, GAME_H, UI } from '../config.js';
import { Keys } from '../core/input.js';
import { Audio } from '../core/audio.js';
import { Session } from '../core/session.js';
import { newGameState } from '../core/state.js';
import { latestSave, eraseSaves } from '../core/save.js';
import { MAPS } from '../data/maps.js';
import { Weather } from '../systems/weather.js';
import { textWidth } from '../art/font.js';
import { txt, panel } from '../ui/widgets.js';
import { formatTime } from './MenuScene.js';

const center = (s) => Math.round((GAME_W - textWidth(s)) / 2);

export class TitleScene extends Phaser.Scene {
  constructor() {
    super('Title');
  }

  create() {
    Audio.setHeartbeat(false);
    this.bg = this.add.image(0, 0, 'bg_title').setOrigin(0);
    this.weather = new Weather(this, 50);
    this.weather.set('title');
    this.logo = this.add.image(GAME_W / 2, 30, 'logo').setOrigin(0.5, 0).setDepth(60);
    this.sub = txt(this, center('A SURVIVAL HORROR ROLE PLAYING GAME'), 91, 'A SURVIVAL HORROR ROLE PLAYING GAME', UI.dim).setDepth(60);
    this.flashRect = this.add.rectangle(0, 0, GAME_W, GAME_H, 0xc8d8f0, 0).setOrigin(0).setDepth(55);
    this.add.tileSprite(0, 0, GAME_W, GAME_H, 'scanlines').setOrigin(0).setDepth(90).setAlpha(0.12);
    this.events.once(Phaser.Scenes.Events.SHUTDOWN, () => this.weather.destroy());

    this.press = txt(this, center('PRESS ANY KEY'), 244, 'PRESS ANY KEY', UI.text).setDepth(60);
    this.credit = txt(this, center('All art and sound generated by code'), GAME_H - 13, 'All art and sound generated by code', UI.faint).setDepth(60);
    this.items = [];
    this.mode = 'press';
    this.anyPressed = false;
    this.prevAny = Keys.onAnyKey;
    Keys.onAnyKey = () => {
      Audio.init();
      this.anyPressed = true;
    };
    this.events.once(Phaser.Scenes.Events.SHUTDOWN, () => { Keys.onAnyKey = () => Audio.init(); });

    Audio.setAmbience('rain');
    Audio.setMusic('title');

    this.overlay = this.add.rectangle(0, 0, GAME_W, GAME_H, 0x000000, 1).setOrigin(0).setDepth(100);
    this.tweens.add({ targets: this.overlay, alpha: 0, duration: 900 });
  }

  buildMenu() {
    this.save = latestSave();
    this.options = [];
    if (this.save) this.options.push({ key: 'continue', label: 'CONTINUE' });
    this.options.push({ key: 'new', label: 'NEW GAME' });
    this.options.push({ key: 'help', label: 'HOW TO PLAY' });
    this.options.push({ key: 'sound', label: 'SOUND' });
    this.index = 0;
    this.drawMenu();
  }

  clearMenu() {
    this.items.forEach((o) => o.destroy());
    this.items = [];
  }

  drawMenu() {
    this.clearMenu();
    const h = this.options.length * 14 + 12;
    const w = 140;
    const x = 26;
    const y = 176;
    const p = panel(this, x, y, w, h, { alpha: 0.86 }).setDepth(60);
    this.items.push(p);
    this.options.forEach((o, i) => {
      const sel = i === this.index;
      const label = o.key === 'sound' ? `SOUND: ${Audio.muted ? 'OFF' : 'ON'}` : o.label;
      this.items.push(txt(this, x + 24, y + 8 + i * 14, label, sel ? UI.accent : UI.text).setDepth(61));
      if (sel) this.items.push(txt(this, x + 12, y + 8 + i * 14, '>', UI.accent).setDepth(61));
    });
    const o = this.options[this.index];
    if (o.key === 'continue' && this.save) {
      const st = this.save.state;
      const info = `${MAPS[st.map] ? MAPS[st.map].name : ''}  -  LV ${st.stats.level}  -  ${formatTime(st.playMs)}`;
      this.items.push(txt(this, x, y - 12, info, UI.dim).setDepth(61));
    }
  }

  drawHelp() {
    this.clearMenu();
    const x = 44;
    const y = 104;
    const w = GAME_W - 88;
    const h = 154;
    this.items.push(panel(this, x, y, w, h, { alpha: 0.96 }).setDepth(60));
    const rows = [
      ['WASD / ARROWS', 'Move. Choose in menus.'],
      ['E / SPACE / ENTER', 'Interact, confirm.'],
      ['ESC / TAB / I', 'Pause menu: items, gear, journal.'],
      ['X / BACKSPACE', 'Go back in menus.'],
      ['M', 'Mute sound.'],
    ];
    rows.forEach(([k, v], i) => {
      this.items.push(txt(this, x + 10, y + 8 + i * 12, k, UI.accent).setDepth(61));
      this.items.push(txt(this, x + 134, y + 8 + i * 12, v, UI.text).setDepth(61));
    });
    const notes = [
      'You are a stray. Reach the house with the yellow window.',
      'Hunger falls as you walk. Eat, or grow weak and starve.',
      'Enemies you see will hunt you. Break line of sight to lose them.',
      'Trash and dead grass rustle. Something may be living in it.',
      'In a fight, read the red warnings and DEFEND before big hits.',
      'Rest and save at dry cardboard boxes.',
    ];
    notes.forEach((n, i) => this.items.push(txt(this, x + 10, y + 74 + i * 12, n, UI.dim).setDepth(61)));
  }

  drawConfirmNew() {
    this.clearMenu();
    const w = 240;
    const x = Math.round((GAME_W - w) / 2);
    const y = 160;
    this.items.push(panel(this, x, y, w, 58, { alpha: 0.96 }).setDepth(60));
    this.items.push(txt(this, x + 12, y + 8, 'Start over? Your old save will be erased.', UI.danger).setDepth(61));
    ['No', 'Yes'].forEach((l, i) => {
      const sel = i === this.confirmIdx;
      this.items.push(txt(this, x + 28, y + 24 + i * 13, l, sel ? UI.accent : UI.text).setDepth(61));
      if (sel) this.items.push(txt(this, x + 16, y + 24 + i * 13, '>', UI.accent).setDepth(61));
    });
  }

  newGame() {
    eraseSaves();
    Session.state = newGameState();
    this.go();
  }

  go() {
    this.mode = 'leaving';
    Audio.play('confirm');
    this.tweens.add({
      targets: this.overlay, alpha: 1, duration: 500,
      onComplete: () => this.scene.start('World'),
    });
  }

  update(time, delta) {
    this.weather.update(delta, this.cameras.main);
    this.flashRect.fillAlpha = this.weather.flash * 0.5;
    this.logo.setAlpha(0.88 + Math.sin(time * 0.002) * 0.04 + (Math.random() < 0.012 ? -0.25 : 0));

    if (this.mode === 'press') {
      this.press.setVisible(Math.floor(time / 600) % 2 === 0);
      if (this.anyPressed) {
        Keys.flush();
        this.press.destroy();
        this.mode = 'menu';
        this.buildMenu();
        Audio.play('select');
      }
      return;
    }
    if (this.mode === 'menu') {
      const n = this.options.length;
      if (Keys.take('up')) {
        this.index = (this.index + n - 1) % n;
        Audio.play('select');
        this.drawMenu();
      }
      if (Keys.take('down')) {
        this.index = (this.index + 1) % n;
        Audio.play('select');
        this.drawMenu();
      }
      if (Keys.take('confirm')) {
        const o = this.options[this.index];
        if (o.key === 'continue') {
          Session.state = this.save.state;
          this.go();
        } else if (o.key === 'new') {
          if (this.save) {
            this.mode = 'confirm';
            this.confirmIdx = 0;
            Audio.play('select');
            this.drawConfirmNew();
          } else {
            this.newGame();
          }
        } else if (o.key === 'help') {
          this.mode = 'help';
          Audio.play('select');
          this.sub.setVisible(false);
          this.drawHelp();
        } else if (o.key === 'sound') {
          Audio.toggleMute();
          Audio.play('select');
          this.drawMenu();
        }
      }
    } else if (this.mode === 'help') {
      if (Keys.take('confirm') || Keys.take('cancel') || Keys.take('menu')) {
        this.mode = 'menu';
        this.sub.setVisible(true);
        Audio.play('cancel');
        this.drawMenu();
      }
    } else if (this.mode === 'confirm') {
      if (Keys.take('up') || Keys.take('down')) {
        this.confirmIdx = 1 - this.confirmIdx;
        Audio.play('select');
        this.drawConfirmNew();
      }
      if (Keys.take('cancel') || Keys.take('menu')) {
        this.mode = 'menu';
        this.drawMenu();
      } else if (Keys.take('confirm')) {
        if (this.confirmIdx === 1) {
          this.newGame();
        } else {
          this.mode = 'menu';
          this.drawMenu();
        }
      }
    }
  }
}
